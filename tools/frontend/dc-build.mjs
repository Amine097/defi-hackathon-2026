// Builds the production pages from the approved Claude Design export (docs/design/claude-design-v2):
//   public/index.html            <- "Faultline Landing v2.dc.html" (template verbatim + the edits listed below)
//   public/assets/dc/landing.js  <- the landing's <script data-dc-script> class (verbatim + the edits listed below)
//   public/app.html              <- "Faultline App.dc.html" (template verbatim + the edits listed below)
// The app's logic class is NOT generated: public/assets/dc/app.js is the design's class wired to the real backend.
//
// Every edit is an exact find/replace that must match; a missing anchor fails the build, so a new export cannot
// drift silently. Figures the landing quotes are filled from recorded backend artifacts and checked here:
//   public/data/recorded/analyze-pt.json        (live /api/analyze run, see scripts/record_demo_payloads.py)
//   data/countermove/demo/latest/summary.json   (recorded local-fork Countermove run, scenario S1)
//
// Run from the repo root:  node tools/frontend/dc-build.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const DESIGN = join(ROOT, 'docs', 'design', 'claude-design-v2');
const PUB = join(ROOT, 'public');
const read = p => readFileSync(p, 'utf8').replace(/\r\n/g, '\n');
const usd = v => '$' + Math.round(v).toLocaleString('en-US');

function rep(src, find, to, { count = 1, label = '' } = {}) {
  const n = src.split(find).length - 1;
  if (n !== count) throw new Error(`dc-build: expected ${count} occurrence(s) of ${label || JSON.stringify(find.slice(0, 80))}, found ${n}`);
  return src.split(find).join(to);
}
function assert(cond, msg) { if (!cond) throw new Error('dc-build: ' + msg); }

function split(html) {
  const x0 = html.indexOf('<x-dc>'), x1 = html.lastIndexOf('</x-dc>') + '</x-dc>'.length;
  const s = html.match(/<script type="text\/x-dc" data-dc-script data-props="([^"]*)">\n([\s\S]*?)\n<\/script>/);
  assert(x0 > 0 && x1 > x0 && s, 'export layout changed (x-dc block or data-dc-script not found)');
  return { template: html.slice(x0, x1), props: s[1], logic: s[2] };
}

const FONTS_GOOGLE = `<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin="">
<link href="https://fonts.googleapis.com/css2?family=Archivo:wdth,wght@62..125,100..900&amp;family=IBM+Plex+Mono:wght@400;500&amp;display=swap" rel="stylesheet">`;
const FONTS_LOCAL = '<link href="/assets/fonts/gf/fonts.css" rel="stylesheet">';

function page({ title, description, scripts, template, props }) {
  return `<!DOCTYPE html>
<!-- GENERATED by tools/frontend/dc-build.mjs from docs/design/claude-design-v2 (Claude Design v2 export). Do not edit:
     change the build script or the export, then rebuild. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${title}</title>
<meta name="description" content="${description}">
<meta name="theme-color" content="#05070b">
<link rel="icon" href="/assets/brand/logo.svg" type="image/svg+xml">
${scripts.map(s => `<script src="${s}"></script>`).join('\n')}
</head>
<body>
${template}
<script type="text/x-dc" data-dc-script data-props="${props}"></script>
</body>
</html>
`;
}

