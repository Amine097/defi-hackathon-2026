const oracle = pt.nodes.find(n => n.id === 'oracle').meta, feed = pt.nodes.find(n => n.id === 'feed').meta;
assert(pt._snapshot && pt.source === 'live', 'analyze-pt.json must be a recorded live run');
assert(oracle.single_feed === true && /^Ojo/.test(feed.description || ''), 'landing says "One Ojo feed": recording disagrees');
assert(/computed on read/.test(oracle.source || '') || /staleness/.test(JSON.stringify(oracle)), 'landing says "computed on read, no staleness guard": recording disagrees');
assert(pt.position.meta.coverage.traced_pct === 0, 'landing says "0% traced to base assets": recording disagrees');
assert(Math.abs(lend.lltv - 0.915) < 1e-9, 'landing says "LLTV 91.5%": recording disagrees');
